const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const wait = () => new Promise((resolve) => setTimeout(resolve, 0));
(async () => {
    const dom = new JSDOM(`<label>Theme<select id="theme"><option value="light">Light</option><option value="dark">Dark</option><option disabled value="no">Disabled</option></select></label><label>Date<input id="date" type="date" value="2026-10-16" min="2026-10-10" max="2026-10-25"></label><label>Time<input id="time" type="time" value="08:00"></label>`, { runScripts: 'outside-only', url: 'https://study.local/settings/' });
    const w = dom.window;
    w.StudyNative = {};
    w.eval(fs.readFileSync(path.resolve(__dirname, '../../assets/form-controls.js'), 'utf8'));
    assert.equal(w.document.querySelectorAll('.app-control-trigger').length, 3);
    const source = w.document.getElementById('theme');
    let changed = 0;
    source.addEventListener('change', () => { changed++; });
    const trigger = source.nextElementSibling;
    trigger.click();
    assert.equal(w.document.querySelector('[role=dialog]').getAttribute('aria-modal'), 'true');
    const options = w.document.querySelectorAll('[role=option]');
    assert.equal(options[2].disabled, true);
    options[1].click();
    await wait();
    assert.equal(source.value, 'dark');
    assert.equal(trigger.textContent, 'Dark');
    assert.equal(changed, 1);
    assert.equal(w.document.activeElement, trigger);
    source.disabled = true;
    await wait();
    assert.equal(trigger.disabled, true);
    w.document.getElementById('date').nextElementSibling.click();
    assert.equal(w.document.querySelector('[aria-label="2026-10-09"]').disabled, true);
    w.document.querySelector('[aria-label="2026-10-20"]').click();
    assert.equal(w.document.getElementById('date').value, '2026-10-20');
    w.document.getElementById('time').nextElementSibling.click();
    const numbers = w.document.querySelectorAll('.app-clock input');
    numbers[0].value = '14'; numbers[1].value = '30';
    [...w.document.querySelectorAll('.app-picker button')].find((button) => button.textContent === 'Выбрать').click();
    assert.equal(w.document.getElementById('time').value, '14:30');
    source.disabled = false;
    await wait();
    trigger.click();
    w.document.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    assert.equal(w.document.querySelector('[role=dialog]'), null);
    source.remove();
    await wait();
    assert.equal(w.document.querySelectorAll('.app-control-trigger').length, 2);
    dom.window.close();
    console.log('Themed controls: select events, disabled states, date bounds, time choice, focus and cleanup passed.');
})().catch((error) => { console.error(error); process.exit(1); });
