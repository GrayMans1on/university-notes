report = []
for name, slug, description in SUBJECTS:
    original = (SOURCE / (name + '.md')).read_text()
    body_start = list(re.finditer(r'^## ', original, re.M))[1].start()
    text = original[body_start:].split('\n## Исходные фотографии')[0]
    text = re.sub(r'^\*Фотографии:.*\n?', '', text, flags=re.M)
    text = re.sub(r'^.*(?:\*\*Преподаватель:\*\*|^Преподаватель:|Сайт преподавателя|^Организационная запись:|Дата в блокноте:|\*\*Для зачёта:\*\*).*\n?', '', text, flags=re.M)
    text = re.sub(r'^Организационные пометки:\n(?:- .*\n)+', '', text, flags=re.M)
    if name == 'История':
        text = re.sub(r'\n### 2\. Баллы и задания[\s\S]*', '', text)
    for old, new in REPLACEMENTS.items():
        text = text.replace(old, new)
    text = re.sub(r'^### \d+\. Преподаватель\s*\n(?:\s*\n)*', '', text, flags=re.M)
    text = re.sub(r'^(#{3}) \d+\. ', r'\1 ', text, flags=re.M)
    text = re.sub(r'\[(?:так читается[^\]]*|[^\]]*читается не[^\]]*|[^\]]*читается рукописная[^\]]*|[^\]]*знак может читаться[^\]]*)\]', '[требует уточнения]', text)
    text = text.replace('[неразборчиво]', '[требует уточнения]')
    text = text.replace('неразборчивы', 'требуют уточнения').replace('неразборчиво', 'требует уточнения')
    text = re.sub(r'(?:На|на|Внизу|внизу|Вверху|вверху) фото(?:графии)? \d+\s*(?:—\s*)?', '', text)
    text = text.replace('на фотографии отсутствует', 'отсутствует').replace('на фотографии', '').replace('на фото', '')
    text = text.replace('в блокноте', 'в черновом решении').replace('В блокноте', 'В черновом решении')
    text = text.replace('из блокнота', 'из чернового решения').replace('ответ блокнота', 'черновой ответ')
    text = text.replace('блокнота', 'чернового решения').replace('рукописного', 'чернового')
    text = text.replace('в исходной записи', 'в черновом варианте').replace('В исходной записи', 'В черновом варианте')
    text = text.replace('формулировка блокнота', 'черновая формулировка')
    text = text.replace('к оригиналу', 'к условию').replace('исходной записи', 'чернового варианта')
    text = text.replace('в оригинале', 'в черновом варианте')
    text = re.sub(r'\n{3,}', '\n\n', text).strip()
    text = '\n'.join(line[0].upper() + line[1:] if re.match(r'^[а-яё]', line) else line for line in text.splitlines())
    text = '# ' + name + '\n\n' + text + '\n'
    (DESTINATION / (name + '.md')).write_text(text)
    report.append({'title': name, 'slug': slug, 'description': description, 'source_bytes': len(original.encode()), 'content_bytes': len(text.encode())})

(DESTINATION / 'subjects.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
print(json.dumps(report, ensure_ascii=False))
